// Post-traitement du G-code CuraEngine pour Klipper (Centauri Carbon, K1) :
// - en-tête/pied au format Orca (temps, filament, vignettes) lus par l'écran des imprimantes ;
// - changements de filament CANVAS (M6211) pour la Centauri Carbon, numéros d'emplacement réels ;
// - suppression des commandes inutiles ou inconnues de Klipper (M105, M205, préchauffes « M104 Tn »).
import { PRINTERS } from '../core/profiles.js';
import { fmtTime } from '../core/gcode.js';
import { canvasChangeBlock, flushVolume } from '../core/materials.js';

export const START_MARK = ';@@SVG2PRINT_START@@';
export const END_MARK = ';@@SVG2PRINT_END@@';
export const LAYERS_MARK = '@@TOTAL_LAYERS@@';

/**
 * raw : G-code CuraEngine ; ctx : { printerId, tools: [{fil, color, slot}], thumbnails, flushMultiplier, name, metadata }
 */
export function postProcess(raw, ctx) {
  const P = PRINTERS[ctx.printerId];
  const tools = ctx.tools;
  const multi = tools.length > 1;
  const filArea = Math.PI * 0.875 * 0.875;
  const lines = raw.split('\n');
  const i0 = lines.findIndex((l) => l.trim() === START_MARK);
  if (i0 < 0) throw new Error('G-code inattendu (marqueur de début absent).');
  // Extrudeur initial choisi par Cura (ligne « Tn » avant le G-code de démarrage)
  let tool = 0;
  for (let k = 0; k < i0; k++) { const m = /^T(\d+)\s*$/.exec(lines[k].trim()); if (m) tool = +m[1]; }
  if (!tools[tool]) tool = 0;
  const initTool = tool;

  const out = [START_MARK];
  let z = 0, layer = -1, layerCount = 0, maxZ = 0, changes = 0;
  let pendingZ = null;
  const usedE = new Array(tools.length).fill(0);
  const flushTotal = new Array(tools.length).fill(0);
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  let inPrint = false;

  for (let i = i0 + 1; i < lines.length; i++) {
    const line = lines[i].replace(/\r$/, '');
    const t = line.trim();
    if (!t) continue;
    let m;
    if ((m = /^T(\d+)\s*$/.exec(t))) {
      const nt = +m[1];
      if (!multi || !tools[nt] || nt === tool) continue;
      const from = tools[tool], to = tools[nt];
      const vol = flushVolume(from.color, to.color, ctx.flushMultiplier || 1);
      out.push(canvasChangeBlock({ next: to.slot, flushVol: vol, oldFil: from.fil, newFil: to.fil, z, maxZ: P.bed.z }));
      flushTotal[nt] += vol;
      changes++;
      tool = nt;
      pendingZ = z;
      continue;
    }
    if (/^M10[49]\s+T\d+/.test(t)) continue; // préchauffe/attente des autres extrudeurs
    if (t === END_MARK) { out.push(END_MARK); continue; }
    if (/^M105\b|^M205\b|^M82\b|^;SETTING_/.test(t)) continue;
    if ((m = /^;LAYER_COUNT:(\d+)/.exec(t))) { layerCount = +m[1]; out.push(t); continue; }
    if ((m = /^;LAYER:(-?\d+)/.exec(t))) {
      layer = +m[1];
      inPrint = true;
      out.push(t);
      if (layer >= 0) {
        if (P.layerStats) out.push(`SET_PRINT_STATS_INFO TOTAL_LAYER=${LAYERS_MARK} CURRENT_LAYER=${layer + 1}`);
        if (layerCount) out.push(`M73 P${Math.floor((layer / layerCount) * 100)}`);
      }
      continue;
    }
    if (/^G[01]\s/.test(t)) {
      const zm = /\bZ(-?[\d.]+)/.exec(t);
      const xm = /\bX(-?[\d.]+)/.exec(t), ym = /\bY(-?[\d.]+)/.exec(t);
      if (zm) { z = +zm[1]; if (inPrint && z > maxZ) maxZ = z; }
      if (pendingZ != null) {
        // Après un changement de filament : on ignore le retour à l'origine de Cura (X0 Y0)
        if (xm && ym && +xm[1] === 0 && +ym[1] === 0) { if (zm) pendingZ = z; continue; }
        if (zm && !xm && !ym) { pendingZ = z; continue; }
        if (xm || ym) {
          out.push(t.replace(/\s*Z-?[\d.]+/, ''));
          out.push(`G1 Z${pendingZ.toFixed(3)} F1200`);
          pendingZ = null;
          continue;
        }
      }
      if (inPrint) {
        const em = /\bE(-?[\d.]+)/.exec(t);
        if (em) usedE[tool] += +em[1];
        if (em && +em[1] > 0) {
          if (xm) { const x = +xm[1]; if (x < minX) minX = x; if (x > maxX) maxX = x; }
          if (ym) { const y = +ym[1]; if (y < minY) minY = y; if (y > maxY) maxY = y; }
        }
      }
    }
    out.push(t);
  }

  // Temps : estimation CuraEngine + changements de filament (purge comprise)
  const meta = ctx.metadata || {};
  let time = (meta.printTime > 0 ? meta.printTime : 0) + 90;
  time += changes * 70 + flushTotal.reduce((a, v) => a + v, 0) / 8;
  const lenMM = usedE.map((e, k) => e + flushLength(flushTotal[k]));
  const grams = lenMM.map((l, k) => (l * filArea * tools[k].fil.density) / 1000);
  const totalLen = lenMM.reduce((a, b) => a + b, 0);
  const totalG = grams.reduce((a, b) => a + b, 0);
  const layers = layerCount || layer + 1;

  const head = [];
  head.push('; HEADER_BLOCK_START');
  head.push('; generated by SVG2Print 1.0 (CuraEngine)');
  head.push(`; model printing time: ${fmtTime(time)}; total estimated time: ${fmtTime(time)}`);
  head.push(`; total layer number: ${layers}`);
  head.push(`; total filament length [mm] : ${lenMM.map((v) => v.toFixed(2)).join(',')}`);
  head.push(`; total filament weight [g] : ${grams.map((v) => v.toFixed(2)).join(',')}`);
  head.push(`; filament_density: ${tools.map((t) => t.fil.density).join(',')}`);
  head.push(`; max_z_height: ${maxZ.toFixed(2)}`);
  head.push('; HEADER_BLOCK_END');
  head.push('');
  if (ctx.thumbnails && ctx.thumbnails.length) {
    head.push('; THUMBNAIL_BLOCK_START');
    for (const th of ctx.thumbnails) {
      head.push(';');
      head.push(`; thumbnail begin ${th.w}x${th.h} ${th.base64.length}`);
      for (let k = 0; k < th.base64.length; k += 78) head.push('; ' + th.base64.slice(k, k + 78));
      head.push('; thumbnail end');
    }
    head.push('; THUMBNAIL_BLOCK_END');
    head.push('');
  }
  head.push(`;TIME:${Math.round(time)}`);
  head.push(`;Filament used: ${(totalLen / 1000).toFixed(4)}m`);
  head.push(`;MINX:${minX.toFixed(2)}\n;MINY:${minY.toFixed(2)}\n;MAXX:${maxX.toFixed(2)}\n;MAXY:${maxY.toFixed(2)}\n;MAXZ:${maxZ.toFixed(2)}`);
  head.push('M73 P0');
  head.push('; EXECUTABLE_BLOCK_START');

  const tail = [];
  tail.push('M73 P100');
  tail.push('; EXECUTABLE_BLOCK_END');
  tail.push('');
  tail.push(`; filament used [mm] = ${lenMM.map((v) => v.toFixed(2)).join(', ')}`);
  tail.push(`; filament used [g] = ${grams.map((v) => v.toFixed(2)).join(', ')}`);
  tail.push(`; total filament used [g] = ${totalG.toFixed(2)}`);
  tail.push(`; estimated printing time (normal mode) = ${fmtTime(time)}`);
  tail.push('; CONFIG_BLOCK_START');
  tail.push(`; printer_model = ${P.name}`);
  tail.push(`; filament_type = ${tools.map((t) => t.fil.type).join(';')}`);
  tail.push(`; filament_settings_id = ${tools.map((t) => `"${t.fil.name}"`).join(';')}`);
  tail.push(`; filament_colour = ${tools.map((t) => (t.color || '#FFFFFF').toUpperCase()).join(';')}`);
  tail.push(`; filament_ids = ${tools.map((t) => t.slot).join(';')}`);
  tail.push(`; nozzle_temperature = ${tools.map((t) => t.fil.nozzle).join(',')}`);
  tail.push(`; bed_temperature = ${tools[0].fil.bed}`);
  tail.push(`; nozzle_diameter = 0.4`);
  tail.push('; CONFIG_BLOCK_END');

  // G-code de démarrage / fin de l'imprimante (filament initial = celui de la 1re couche)
  const f0 = tools[initTool].fil;
  const startG = P.startGcode({
    tool: tools[initTool].slot, type: f0.type, nozzleFirst: f0.nozzleFirst, bedFirst: f0.bedFirst, totalLayers: layers,
    pressureAdvance: f0.pressureAdvance, accelFirst: Math.min(P.speeds.accelFirst, f0.accelCap || Infinity), maxZ,
    purgeF: Math.round(Math.min(6000, Math.max(900, (f0.maxVolumetric / 0.5 / 0.3) * 60))),
  });
  const body = out.join('\n')
    .replace(START_MARK, startG + '\nM83\nG90')
    .replace(END_MARK, 'M106 S0\n' + P.endGcode({ maxZ }));
  const gcode = (head.join('\n') + '\n' + body + '\n' + tail.join('\n') + '\n').split(LAYERS_MARK).join(String(layers));
  return {
    gcode,
    stats: {
      timeSec: time, layers, maxZ, changes,
      perTool: tools.map((t, k) => ({ slot: t.slot, color: t.color, name: t.fil.name, mm: lenMM[k], g: grams[k] })),
      grams: totalG, filamentMM: totalLen,
      bounds: { minX, maxX, minY, maxY },
    },
  };
}

const flushLength = (vol) => vol / (Math.PI * 0.875 * 0.875);

/**
 * Lecture du G-code pour l'aperçu : segments d'extrusion par couche.
 * Renvoie { layers: [{z, start, count}], pos: Float32Array (x,y,z ×2 par segment), kind: Uint8Array, tool: Uint8Array }
 */
export const KINDS = { 'WALL-OUTER': 1, 'WALL-INNER': 2, FILL: 3, SKIN: 4, SUPPORT: 5, 'SUPPORT-INTERFACE': 6, SKIRT: 7, 'PRIME-TOWER': 8 };
export function parsePreview(gcode, maxSegments = 2500000) {
  const lines = gcode.split('\n');
  let x = 0, y = 0, z = 0, kind = 0, tool = 0, inPrint = false;
  const pos = [], kinds = [], tls = [], layers = [];
  let cur = null;
  const toolOfSlot = new Map();
  for (const raw of lines) {
    const l = raw;
    const c = l.charCodeAt(0);
    if (c === 59) { // ';'
      if (l.startsWith(';LAYER:')) {
        inPrint = true;
        cur = { z, start: kinds.length, count: 0 };
        layers.push(cur);
      } else if (l.startsWith(';TYPE:')) kind = KINDS[l.slice(6).trim()] || 0;
      continue;
    }
    if (c === 84 /* T */ && /^T\d+$/.test(l.trim())) {
      const s = +l.trim().slice(1);
      if (!toolOfSlot.has(s)) toolOfSlot.set(s, toolOfSlot.size);
      tool = s; continue;
    }
    if (c !== 71 /* G */ || (l[1] !== '0' && l[1] !== '1') || l[2] !== ' ') continue;
    let nx = x, ny = y, nz = z, e = 0;
    const parts = l.split(' ');
    for (let k = 1; k < parts.length; k++) {
      const p = parts[k], ch = p.charCodeAt(0);
      if (ch === 88) nx = +p.slice(1); else if (ch === 89) ny = +p.slice(1); else if (ch === 90) nz = +p.slice(1); else if (ch === 69) e = +p.slice(1); else if (ch === 59) break;
    }
    if (inPrint && l[1] === '1' && e > 0 && (nx !== x || ny !== y) && kinds.length < maxSegments) {
      pos.push(x, y, nz, nx, ny, nz);
      kinds.push(kind);
      tls.push(tool);
      if (cur) { cur.count++; if (nz > cur.z) cur.z = nz; }
    }
    x = nx; y = ny; z = nz;
  }
  return { layers: layers.filter((L) => L.count > 0), pos: new Float32Array(pos), kind: Uint8Array.from(kinds), tool: Uint8Array.from(tls) };
}
