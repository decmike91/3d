import fs from 'fs';
import { DOMParser } from '@xmldom/xmldom';
import { parseSVG, bounds, SCALE } from '../src/core/svg.js';
import { transformPattern } from '../src/core/slicer.js';
import { slice } from '../src/core/gcode.js';
import { defaultFilament, defaultPrint, PRINTERS } from '../src/core/profiles.js';
const file = process.argv[2] || 'test/sample.svg';
const printer = process.argv[3] || 'cc';
const polarity = process.argv[4] || 'positive';
const r = parseSVG(fs.readFileSync(file,'utf8'), { DOMParser });
console.log('warnings', r.warnings, 'paths', r.paths.length);
const b = bounds(r.paths); console.log('bbox mm', b.w/SCALE, b.h/SCALE);
const P = PRINTERS[printer];
const pat = transformPattern(r.paths, { mirrorX:false, rotation:0, width:100, centerX:P.bed.x/2, centerY:P.bed.y/2 });
const b2=bounds(pat); console.log('placed', b2.minX/SCALE,b2.minY/SCALE,b2.maxX/SCALE,b2.maxY/SCALE);
const print = { ...defaultPrint(printer), polarity };
const t0=Date.now();
const res = slice(pat, printer, print, defaultFilament(printer), {});
console.log('slice ms', Date.now()-t0, res.stats);
fs.writeFileSync(`test/out_${printer}_${polarity}.gcode`, res.gcode);
fs.writeFileSync(`test/out_${printer}_${polarity}.preview.json`, JSON.stringify(res.preview));
