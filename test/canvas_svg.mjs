// CANVAS dans l'onglet Relief SVG : plaque (emplacement 1, PETG) puis motif (emplacement 3, PLA)
import fs from 'fs';
import { DOMParser } from '@xmldom/xmldom';
import { parseSVG } from '../src/core/svg.js';
import { transformPattern } from '../src/core/slicer.js';
import { slice } from '../src/core/gcode.js';
import { defaultFilament, defaultPrint, PRINTERS } from '../src/core/profiles.js';
import { materialProfile, flushVolume } from '../src/core/materials.js';
let ok = true;
const check = (c, m) => { console.log(`${c ? 'OK ' : 'ÉCHEC'} ${m}`); if (!c) ok = false; };
const r = parseSVG(fs.readFileSync('test/sample.svg', 'utf8'), { DOMParser });
const P = PRINTERS.cc;
const pat = transformPattern(r.paths, { rotation: 0, width: 100, centerX: P.bed.x / 2, centerY: P.bed.y / 2 });
const print = { ...defaultPrint('cc'), polarity: 'positive' };
const canvas = { plateTool: 0, reliefTool: 2, reliefFil: materialProfile('pla_hs', 'cc'), flushVol: flushVolume('#FFFFFF', '#000000'), colors: { 0: '#FFFFFF', 2: '#000000' } };
const res = slice(pat, 'cc', print, defaultFilament('cc', 'petg_hs'), { canvas });
const g = res.gcode;
fs.writeFileSync('test/out_cc_canvas.gcode', g);
const changes = g.match(/^M6211 T\d.*$/gm) || [];
check(changes.length === 1 && /^M6211 T2 L\d/.test(changes[0]), `un seul changement, vers l’emplacement 3 : ${changes[0]}`);
const iChange = g.indexOf('M6211 T2 L');
const zBefore = [...g.slice(0, iChange).matchAll(/^;Z:([\d.]+)/gm)].pop()?.[1];
check(Math.abs(+zBefore - print.plateThickness) < 0.01, `changement après la dernière couche de plaque (z = ${zBefore} mm)`);
check(/^T0 ; filament initial/m.test(g) && /^M6211 A1 L200 T0 Q245/m.test(g), 'démarrage sur l’emplacement 1 en PETG (245 °C)');
check(/^M109 S220$/m.test(g.slice(iChange)), 'motif à 220 °C (PLA)');
check(/; filament_type = PETG;PLA/.test(g) && /; filament_colour = #FFFFFF;#000000/.test(g), 'en-tête : 2 filaments et couleurs');
check(JSON.stringify(res.stats.tools) === '[0,2]', 'emplacements utilisés renvoyés (0 et 2)');
const single = slice(pat, 'cc', print, defaultFilament('cc', 'pla_hs'), {});
check(!/^M6211 T/m.test(single.gcode) && /initial_filament:PLA/.test(single.gcode), 'sans CANVAS : aucun changement, matière PLA en en-tête');
console.log(ok ? 'RÉSULTAT : OK' : 'RÉSULTAT : ÉCHEC');
process.exit(ok ? 0 : 1);
